CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  login_id VARCHAR(100) NOT NULL UNIQUE,
  display_name VARCHAR(100) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('ADMIN','USER') NOT NULL DEFAULT 'USER',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
  token_version INT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS print_records (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NULL,
  printer_key VARCHAR(100) NOT NULL,
  title VARCHAR(255) NOT NULL,
  file_name VARCHAR(255) NULL,
  reservation_start DATETIME(3) NULL,
  reservation_end DATETIME(3) NULL,
  reservation_status ENUM('NONE','BOOKED','CANCELLED','EXPIRED') NOT NULL DEFAULT 'NONE',
  print_status ENUM('NOT_STARTED','PRINTING','PAUSED','COMPLETED','FAILED','CANCELLED','UNKNOWN') NOT NULL DEFAULT 'NOT_STARTED',
  started_at DATETIME(3) NULL,
  finished_at DATETIME(3) NULL,
  external_job_id VARCHAR(255) NULL,
  job_key VARCHAR(255) NULL UNIQUE,
  ownership_status ENUM('UNASSIGNED','CONFIRMED') NOT NULL DEFAULT 'UNASSIGNED',
  armed_at DATETIME(3) NULL,
  armed_until DATETIME(3) NULL,
  estimated_filament_g DECIMAL(12,3) NULL,
  actual_filament_g DECIMAL(12,3) NULL,
  filament_source VARCHAR(30) NULL,
  filament_details JSON NULL,
  metadata JSON NULL,
  version INT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_print_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT ck_reservation_pair CHECK ((reservation_start IS NULL AND reservation_end IS NULL) OR (reservation_start IS NOT NULL AND reservation_end IS NOT NULL AND reservation_start < reservation_end)),
  CONSTRAINT ck_filament_nonnegative CHECK ((estimated_filament_g IS NULL OR estimated_filament_g >= 0) AND (actual_filament_g IS NULL OR actual_filament_g >= 0)),
  INDEX ix_user_started (user_id, started_at),
  INDEX ix_printer_reservation (printer_key, reservation_status, reservation_start, reservation_end),
  INDEX ix_printer_print (printer_key, print_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
